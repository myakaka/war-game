/** 현재 언어 (화면 스크립트가 setLang 으로 바꿈). 로직·시뮬레이션은 언어와 무관하게 같은 결과를 냄 */
let CURRENT_LANG = 'ko';
function setLang(lang) { CURRENT_LANG = STRINGS[lang] ? lang : 'ko'; }
function getLang() { return CURRENT_LANG; }
/** 문자열 키 → 현재 언어 문장. 없는 키는 한국어, 그래도 없으면 키 그대로 */
function t(key, params) {
  let s = (STRINGS[CURRENT_LANG] || STRINGS.ko)[key];
  if (s == null) s = STRINGS.ko[key];
  if (s == null) return key;
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => {
    if (!(k in params)) return m;
    const v = params[k];
    if (Array.isArray(v)) return v.map((x) => (x && typeof x === 'object' ? t(x.t, x.p) : String(x))).join(t('intro.listSep'));   // 목록
    return v && typeof v === 'object' ? t(v.t, v.p) : String(v);
  });
}
